"""`build`: index.html from animation.json, content.json and the chapters."""
from __future__ import annotations

import hashlib
import html
import json
from pathlib import Path

from .common import HAError
from .lib_pin import PINS
from .project import Project

BASE_CSS = """html, body { margin: 0; height: 100%; overflow: hidden; background: #000; }
#ha-stage { position: absolute; left: 0; top: 0; overflow: hidden; transform-origin: 0 0; background: #fff; }
#ha-stage > section.ha-chapter { position: absolute; left: 0; top: 0; width: 100%; height: 100%; overflow: hidden; }
#ha-bar { position: fixed; left: 0; right: 0; bottom: 0; display: flex; gap: 12px; align-items: center;
  padding: 8px 12px; background: rgba(0, 0, 0, 0.6); color: #fff; font: 13px system-ui, sans-serif; }
#ha-bar button { min-width: 64px; }
#ha-bar input { flex: 1; }"""


class Builder:
    """Writes the project's index.html; `render()` returns the text without writing it."""

    def __init__(self, project: Project) -> None:
        self.project = project

    def render(self) -> str:
        p = self.project
        animation = p.load()
        if not animation.chapters:
            raise HAError("animation.json has no chapters; add one with add-chapter")
        if not p.player_js.is_file():
            raise HAError(f"{p.player_js} not found; run init")
        content = p.content()
        sections = []
        scripts = []
        for c in animation.chapters:
            for path in (p.chapter_html(c.id), p.chapter_js(c.id)):
                if not path.is_file():
                    raise HAError(f"{path} not found")
            body = p.chapter_html(c.id).read_text(encoding="utf-8").strip()
            sections.append(f'<section id="ch-{c.id}" class="ha-chapter" data-chapter="{c.id}">\n{body}\n</section>')
            scripts.append(self._script(f"chapters/{c.id}.js"))
        libs = [self._script(f"lib/{PINS[k].file}") for k in p.libs()]
        if animation.lib.value not in p.libs():
            raise HAError(f"lib/{PINS[animation.lib.value].file} not found; run init --lib {animation.lib.value}")
        config = {**animation.to_dict(), "content": content}
        config_js = json.dumps(config, ensure_ascii=False).replace("</", "<\\/")
        lines = [
            "<!doctype html>",
            '<html lang="en">',
            "<head>",
            '<meta charset="utf-8">',
            '<meta name="viewport" content="width=device-width, initial-scale=1">',
            "<!-- Generated by html-animation build from animation.json, content.json and chapters/. -->",
            f"<title>{html.escape(animation.title)}</title>",
            f"<style>\n{BASE_CSS}\n</style>",
            "</head>",
            "<body>",
            f'<div id="ha-stage" style="width: {animation.width}px; height: {animation.height}px;">',
            *sections,
            "</div>",
            f"<script>window.HA_CONFIG = {config_js};</script>",
            *libs,
            self._script("player.js"),
            *scripts,
            "<script>HA.start();</script>",
            "</body>",
            "</html>",
        ]
        return "\n".join(lines) + "\n"

    def _script(self, rel: str) -> str:
        """A script tag with a content hash in the query, so a reloaded page never runs a cached old file."""
        digest = hashlib.sha256((self.project.folder / rel).read_bytes()).hexdigest()[:12]
        return f'<script src="{rel}?v={digest}"></script>'

    def build(self) -> dict:
        text = self.render()
        self.project.index_html.write_text(text, encoding="utf-8")
        a = self.project.load()
        return {"index": str(self.project.index_html), "duration": a.duration,
                "chapters": [c.id for c in a.chapters]}

    def current(self) -> bool:
        """Whether index.html equals what build writes now."""
        path: Path = self.project.index_html
        return path.is_file() and path.read_text(encoding="utf-8") == self.render()

"""SUGGESTED manim scene `__SCENE_ID__`: a moving skeleton. A dot, driven by
a ValueTracker, runs round a ring for the whole narration, and the shape at
the centre turns into the next one during each sentence. Replace the objects
with the ones the brief describes and keep the pattern: something runs from
one cue to the next, one transformation per sentence, and the last 0.5 s is
still (references/manim.md, "Movement").

`sv_timing.py` (generated by scaffold, do not edit) holds the narration
times: S(n) / SE(n) are the start / end of sentence n, W(n, "word") /
WE(n, "word") of a word in it (W(n, "word", 2) for its second occurrence).
`self.at(t)` waits until scene time t; `self.finish()` waits until the end of
the narration and must be the last call of `construct`.

A word cue, with the word as a variable or literal:

    self.at(W(2, word))
    self.play(Indicate(label), run_time=0.5)
"""

from pathlib import Path

from manim import (BLUE, WHITE, YELLOW, Circle, Dot, ImageMobject, RegularPolygon, Square, Transform,
                   ValueTracker, always_redraw, config, linear)

from sv_timing import DURATION, TIMING, S, TimedScene

BACKGROUND_COLOR = __BACKGROUND_COLOR__
# The scene's image (`Image:` in the storyboard), copied here by scaffold.
BACKGROUND = Path(__file__).with_name("__BACKGROUND__")
# What each sentence shows (the On screen cells); build the movement from them.
BEATS = __BEATS__


class __SCENE_CLASS__(TimedScene):
    def construct(self):
        self.camera.background_color = BACKGROUND_COLOR
        if BACKGROUND.is_file():
            # The image fitted inside the frame.
            bg = ImageMobject(str(BACKGROUND))
            bg.height = config.frame_height
            if bg.width > config.frame_width:
                bg.width = config.frame_width
            self.add(bg)

        n = len(TIMING["sentences"])
        end = DURATION - 0.5
        frame = 1 / config.frame_rate

        # A value from 0 to 1 over the narration moves the dot round the ring.
        progress = ValueTracker(0)
        ring = Circle(radius=2.8, color=WHITE, stroke_opacity=0.35)
        dot = always_redraw(lambda: Dot(ring.point_from_proportion(progress.get_value() % 1),
                                        radius=0.14, color=YELLOW))
        shapes = [Circle(radius=1.2, color=BLUE, fill_opacity=0.6),
                  Square(side_length=2.2, color=YELLOW, fill_opacity=0.6),
                  RegularPolygon(n=6, color=WHITE, fill_opacity=0.6).scale(1.3)]
        shape = shapes[0].copy().scale(0.2)
        self.add(ring, dot, shape)

        # One transformation per sentence, running until the next sentence starts.
        for i in range(1, n + 1):
            self.at(S(i))
            stop = min(S(i + 1) if i < n else end, end)
            target = shapes[i % len(shapes)].copy().rotate(0.6 * i)
            self.play(Transform(shape, target), progress.animate.set_value(i / n),
                      run_time=max(stop - self.time, frame), rate_func=linear)
        self.finish()

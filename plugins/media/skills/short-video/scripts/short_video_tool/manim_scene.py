"""Manim scenes: scaffold and render a scene with `Engine: manim`.

A manim scene version (`scenes/<scene>/v<N>/`) holds `scene.py`, written by
the scene author from the starting page `assets/manim_scene.py`, and
`sv_timing.py`, generated from the narration's `timing.json` on every
scaffold: `TIMING`, the S / SE / W / WE helpers of `timing.js`, `DURATION`
and `TimedScene` (a Manim Scene with `at(t)` and `finish()`). It also holds
`timing.json`, `brief.md`, `voice_version` and, when the scene has an image,
`background.png`.

`render` checks the helper calls in `scene.py`, runs `manim render` from the
separate uv project `scripts/manim/` in its own environment
(`config.manim_env()`), with Manim's media directory inside the version, and
copies the video to `silent.mp4` with its sample aspect ratio set to 1:1 (as
HyperFrames writes it), so `assemble` can join it with HTML scenes. After a
length check against the narration it muxes, writes the contact sheet and
`meta.json` as `scenes.render` does, with `"engine": "manim"` in `meta.json`.
"""

from __future__ import annotations

import json
import keyword
import os
import pprint
import re
import shutil
from pathlib import Path

from . import config, media, settings, state, storyboard, versions
from .engine import Engine
from .scenes import BACKGROUND, SceneError, _latest_timing, _scene_voice, brief_markdown, check_helpers, finish

ENGINE = Engine.MANIM
SCENE_PY = "scene.py"
TIMING_PY = "sv_timing.py"
MEDIA_DIR = "media"
HELPERS_ASSET = "manim-timing-helpers.py"
STARTING_PAGE = "manim_scene.py"
# `W(1, "word", k=2)`: the occurrence as a keyword argument, checked as a positional one.
_K_KEYWORD = re.compile(r"(\b(?:W|WE)\s*\([^()]*?,\s*)k\s*=\s*(\d+\s*\))")


def _m() -> dict:
    return settings.get()["manim"]


def is_manim(scene: dict) -> bool:
    return scene.get("engine") == ENGINE


# ---------------------------------------------------------------------------
# Pure helpers


def timing_data(timing: dict) -> dict:
    """The fields of `timing.json` that `TIMING` holds (as in timing.js)."""
    return {
        "duration": timing["duration"],
        "sentences": [
            {
                "index": s["index"],
                "text": s["text"],
                "start": s["start"],
                "end": s["end"],
                "words": [{"text": w["text"], "start": w["start"], "end": w["end"]} for w in s.get("words", [])],
            }
            for s in timing["sentences"]
        ],
    }


def sv_timing_py(timing: dict, source: str = "") -> str:
    """`sv_timing.py`: `TIMING` plus the helpers in `assets/manim-timing-helpers.py`."""
    header = (f"# Generated by short-video scaffold{' from ' + source if source else ''}. Do not edit.\n"
              "# Times are seconds of scene time.\n")
    return (header + "TIMING = " + pprint.pformat(timing_data(timing), indent=1, width=110, sort_dicts=False)
            + "\n" + settings.asset(HELPERS_ASSET))


def scene_class() -> str:
    """`manim.scene_class`, refused unless it is a Python identifier."""
    name = _m()["scene_class"]
    if not isinstance(name, str) or not name.isidentifier() or keyword.iskeyword(name):
        raise SceneError(f"`manim.scene_class` must be a Python class name, not {name!r}")
    return name


def render_starting_page(scene: dict) -> str:
    """The starting page `assets/manim_scene.py` with the scene id, class,
    beats and background colour filled in."""
    m = _m()
    return (settings.asset(STARTING_PAGE)
            .replace("__SCENE_ID__", scene["id"])
            .replace("__SCENE_CLASS__", scene_class())
            .replace("__BACKGROUND_COLOR__", repr(str(m["background_color"])))
            .replace("__BACKGROUND__", BACKGROUND)
            .replace("__BEATS__", repr([str(b) for b in scene.get("beats") or []])))


def check_scene_py(text: str, timing: dict) -> tuple[list[str], int]:
    """`scenes.check_helpers` on Python source; `k=N` counts as the occurrence."""
    return check_helpers(_K_KEYWORD.sub(r"\1\2", text), timing)


def manim_brief(scene: dict, timing: dict, voice_version: str) -> str:
    """`brief.md` of an HTML scene plus a section on the manim files."""
    v = settings.get()["video"]
    return brief_markdown(scene, timing, voice_version) + "\n".join([
        "## Manim",
        "",
        f"- Engine: Manim Community Edition. Write the animation in `{SCENE_PY}`; `render` renders "
        f"class `{scene_class()}` (`manim.scene_class`, a `TimedScene`); `references/manim.md` has the rules.",
        f"- `{TIMING_PY}` holds the times above as `S`/`SE`/`W`/`WE`; it is generated, do not edit it.",
        f"- Render: {v['width']}x{v['height']}, {v['fps']} fps; end `construct` with `self.finish()`.",
        "",
    ])


def length_ok(video_seconds: float, narration_seconds: float) -> bool:
    """The video is within `manim.length_tolerance_frames` frames of the narration."""
    fps = settings.get()["video"]["fps"]
    return abs(video_seconds - narration_seconds) <= _m()["length_tolerance_frames"] / fps + 1e-6


def manim_command(sdir: Path) -> list[str]:
    """`uv run --project scripts/manim manim render ...` for the version `sdir`."""
    v, m = settings.get()["video"], _m()
    return [media.which("uv"), "run", "--project", str(config.MANIM_PROJECT),
            "manim", "render", "-r", f"{v['width']},{v['height']}", "--fps", str(v["fps"]),
            "--format", "mp4", "--media_dir", str(sdir / MEDIA_DIR), "-o", "silent",
            "--disable_caching", "--progress_bar", "none", "-v", str(m["verbosity"]),
            # --silent: no check of PyPI for a newer Manim after the render.
            "--silent",
            str(sdir / SCENE_PY), scene_class()]


def manim_env_vars(base: dict | None = None) -> dict:
    """The environment for the Manim subprocess: uv's project environment is
    the Manim one, never short-video's."""
    venv = config.manim_env()
    if venv is None:
        raise SceneError("PLUGIN_ENV_DIR is not set, so the Manim environment has no place outside the "
                         "plugin directory; run short-video through its wrapper short-video.sh")
    env = dict(os.environ if base is None else base)
    env.pop("VIRTUAL_ENV", None)
    env["UV_PROJECT_ENVIRONMENT"] = str(venv)
    return env


# ---------------------------------------------------------------------------
# Scaffold / render


def scaffold(project: Path, scene: dict) -> Path:
    """Create the next version of a manim scene and return its directory."""
    sid = scene["id"]
    if not is_manim(scene):
        raise SceneError(f"scene {sid} is not a manim scene")
    vdir, timing = _latest_timing(project, sid)
    image = storyboard.image_path(project, scene["image"]) if scene.get("image") else None
    if image is not None and not image.is_file():
        raise SceneError(f"scene {sid}: image {image} not found")

    previous = state.latest_scene(project, sid)
    out = versions.next_version(state.scene_root(project, sid))
    if previous is not None and (previous / SCENE_PY).is_file():
        shutil.copyfile(previous / SCENE_PY, out / SCENE_PY)
    else:
        (out / SCENE_PY).write_text(render_starting_page(scene), encoding="utf-8")
    (out / TIMING_PY).write_text(sv_timing_py(timing, f"voice/{sid}/{vdir.name}/timing.json"), encoding="utf-8")
    (out / "timing.json").write_text(json.dumps(timing, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    if image is not None:
        shutil.copyfile(image, out / BACKGROUND)
    (out / "brief.md").write_text(manim_brief(scene, timing, vdir.name), encoding="utf-8")
    (out / "voice_version").write_text(vdir.name + "\n")
    return out


def _manim_video(sdir: Path) -> Path:
    found = sorted((sdir / MEDIA_DIR / "videos").glob("**/silent.mp4"))
    if not found:
        raise SceneError(f"manim wrote no silent.mp4 under {sdir / MEDIA_DIR}")
    return max(found, key=lambda p: p.stat().st_mtime)


def render(project: Path, scene: dict) -> Path:
    """Static check, Manim render, length check, mux narration, contact sheet,
    meta. Returns scene.mp4."""
    sid = scene["id"]
    sdir = state.latest_scene(project, sid)
    if sdir is None or not (sdir / SCENE_PY).is_file():
        raise SceneError(f"scene {sid}: no manim scene to render; run `scaffold` first")
    py_path = sdir / SCENE_PY
    timing = json.loads((sdir / "timing.json").read_text(encoding="utf-8"))
    vdir = _scene_voice(project, sdir)

    errors, _ = check_scene_py(py_path.read_text(encoding="utf-8"), timing)
    if errors:
        raise SceneError(f"{py_path}: timing helper calls do not match timing.json:\n" + "\n".join(errors))

    env = manim_env_vars()
    media.run(manim_command(sdir), cwd=sdir, env=env)

    ffmpeg = media.which("ffmpeg")
    silent = sdir / "silent.mp4"
    # Manim leaves the sample aspect ratio unset; HyperFrames writes 1:1.
    # Setting it in the stream lets `assemble` concat both kinds of scene.
    media.run([ffmpeg, "-y", "-v", "error", "-i", _manim_video(sdir), "-map", "0:v:0", "-c:v", "copy",
               "-bsf:v", "h264_metadata=sample_aspect_ratio=1", silent])
    video_seconds = media.video_duration(silent)
    if not length_ok(video_seconds, timing["duration"]):
        fps = settings.get()["video"]["fps"]
        raise SceneError(
            f"{py_path}: the video is {video_seconds:.3f} s, the narration {timing['duration']:.3f} s "
            f"(more than {_m()['length_tolerance_frames']} frame(s) at {fps} fps apart); "
            "end `construct` with `self.finish()` and keep the animations before it within the narration")

    return finish(sdir, silent, ["-i", vdir / "narration.wav"],
                  {"scene": sid, "voice_version": vdir.name, "engine": ENGINE})

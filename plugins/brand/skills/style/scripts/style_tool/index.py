"""Render references/index.md and references/catalogue.json from the front matter of references/<name>.md."""

from __future__ import annotations

import json
from pathlib import Path

import yaml

SKILL_DIR = Path(__file__).resolve().parents[2]
REFERENCES = SKILL_DIR / "references"
INDEX_FILE = REFERENCES / "index.md"
CATALOGUE_FILE = REFERENCES / "catalogue.json"
HEADER = "# Style index\n\nOne line per style: name, tags, suits, description. Generated by `style.sh index` from `references/<name>.md`.\n"


class StyleError(Exception):
    pass


def front_matter(path: Path) -> dict:
    """The YAML front matter of a style file as a dict."""
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---\n"):
        raise StyleError(f"{path}: no front matter")
    end = text.find("\n---\n", 4)
    if end < 0:
        raise StyleError(f"{path}: front matter not closed")
    try:
        data = yaml.safe_load(text[4:end])
    except yaml.YAMLError as e:
        raise StyleError(f"{path}: front matter does not parse: {e}") from e
    if not isinstance(data, dict):
        raise StyleError(f"{path}: front matter is not a mapping")
    return data


def style_files(references: Path = REFERENCES) -> list[Path]:
    """Every style file in `references`, sorted by name (index.md excluded)."""
    return sorted(p for p in references.glob("*.md") if p.name != INDEX_FILE.name)


def check_optional(path: Path, meta: dict) -> None:
    """`title`, when present, is a non-empty string; `links`, when present, is a non-empty mapping of label to an
    http(s) URL."""
    if "title" in meta and not (isinstance(meta["title"], str) and meta["title"].strip()):
        raise StyleError(f"{path}: title is not a non-empty string")
    if "links" in meta:
        links = meta["links"]
        if not (isinstance(links, dict) and links):
            raise StyleError(f"{path}: links is not a mapping of label to URL")
        for label, url in links.items():
            if not (isinstance(label, str) and isinstance(url, str) and url.startswith(("https://", "http://"))):
                raise StyleError(f"{path}: link {label!r} is not a label with an http(s) URL")


def styles(references: Path = REFERENCES) -> list[dict]:
    """The front matter of every style file, sorted by name; each must have name, description, tags and suits."""
    metas = []
    for path in style_files(references):
        meta = front_matter(path)
        missing = [k for k in ("name", "description", "tags", "suits") if not meta.get(k)]
        if missing:
            raise StyleError(f"{path}: missing {', '.join(missing)}")
        check_optional(path, meta)
        metas.append(meta)
    return sorted(metas, key=lambda m: m["name"])


def render_index(references: Path = REFERENCES) -> str:
    """The text of index.md: a header, then `- name [tags] (suits: ...): description` per style, sorted by name."""
    lines = []
    for meta in styles(references):
        tags = ", ".join(meta["tags"])
        suits = ", ".join(meta["suits"])
        lines.append(f"- {meta['name']} [{tags}] (suits: {suits}): {meta['description']}")
    return HEADER + "\n" + "\n".join(lines) + "\n"


def render_catalogue(references: Path = REFERENCES) -> str:
    """The text of catalogue.json: a JSON array sorted by name of {name, description, tags, suits, sample}, plus
    `title` and `links` when the style file has them, where sample is `assets/<name>.png` relative to the skill
    directory (the parent of `references`), or null when that file does not exist (no sample image yet)."""
    skill_dir = references.parent
    entries = []
    for meta in styles(references):
        sample = f"assets/{meta['name']}.png"
        if not (skill_dir / sample).is_file():
            sample = None
        entry = {k: meta[k] for k in ("name", "title", "description", "tags", "suits", "links") if k in meta}
        entries.append(entry | {"sample": sample})
    return json.dumps(entries, indent=2, ensure_ascii=False) + "\n"

